-- Runs unchanged on PostgreSQL (prod) and on H2 in PostgreSQL mode (dev/tests).

CREATE TABLE orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         VARCHAR(64)    NOT NULL,
    currency            VARCHAR(3)     NOT NULL,
    status              VARCHAR(16)    NOT NULL,
    total_amount        NUMERIC(14, 2) NOT NULL,
    idempotency_key     VARCHAR(255),
    request_fingerprint VARCHAR(64),
    cancellation_reason VARCHAR(255),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at        TIMESTAMP WITH TIME ZONE,
    cancelled_at        TIMESTAMP WITH TIME ZONE,
    version             BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_orders_total CHECK (total_amount >= 0),
    -- The database, not application code, is the final guard against a duplicate create under a race.
    CONSTRAINT uq_orders_idempotency_key UNIQUE (idempotency_key)
);

-- Serves "list by customer [and status], newest first" and "list by status, newest first".
CREATE INDEX ix_orders_customer_status_created ON orders (customer_id, status, created_at DESC);
CREATE INDEX ix_orders_status_created ON orders (status, created_at DESC);
CREATE INDEX ix_orders_created ON orders (created_at DESC);

CREATE TABLE order_lines (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_number  INT            NOT NULL,
    sku          VARCHAR(64)    NOT NULL,
    product_name VARCHAR(200)   NOT NULL,
    quantity     INT            NOT NULL,
    unit_price   NUMERIC(12, 2) NOT NULL,
    line_total   NUMERIC(14, 2) NOT NULL,
    CONSTRAINT ck_order_lines_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_lines_price CHECK (unit_price > 0),
    CONSTRAINT uq_order_lines_number UNIQUE (order_id, line_number)
);
